const DICTS: Record<Language, Dict> = { pt: PT, en: EN, es: ES }

interface I18nContextValue {
  language: Language
  setLanguage: (l: Language) => void
  t: (key: string) => string
}

const I18nContext = createContext<I18nContextValue | null>(null)

const STORAGE_KEY = 'phl.language'

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<Language>('pt')

  useEffect(() => {
    // diferido: evita setState síncrono no corpo do effect (cascata de render)
    const timer = setTimeout(() => {
      const stored = window.localStorage.getItem(STORAGE_KEY)
      if (stored === 'en' || stored === 'es' || stored === 'pt') {
        setLanguageState(stored)
      } else {
        // sync com o tenant (server é a fonte de verdade)
        apiFetch('/api/settings')
          .then((r) => (r.ok ? r.json() : null))
          .then((data: { language?: string } | null) => {
            if (data?.language === 'en' || data?.language === 'es' || data?.language === 'pt') {
              setLanguageState(data.language)
            }
          })
          .catch(() => undefined)
      }
    }, 0)
    return () => clearTimeout(timer)
  }, [])

  const setLanguage = useCallback((l: Language) => {
    setLanguageState(l)
    window.localStorage.setItem(STORAGE_KEY, l)
    void apiFetch('/api/settings', {
      method: 'PUT',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ language: l }),
    }).catch(() => undefined)
  }, [])

  const t = useCallback(
    (key: string) => DICTS[language][key] ?? PT[key] ?? key,
    [language],
  )

  const value = useMemo(() => ({ language, setLanguage, t }), [language, setLanguage, t])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n fora do LanguageProvider')
  return ctx
}
